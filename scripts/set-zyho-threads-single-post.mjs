import { Client as PgClient } from "pg";
import { MongoClient } from "mongodb";

const databaseUrl = process.env.DATABASE_URL?.trim();

if (!databaseUrl) {
  console.error("DATABASE_URL is required.");
  process.exit(1);
}

const pg = new PgClient({ connectionString: databaseUrl });
await pg.connect();

let mongo;

try {
  const result = await pg.query(
    `select
       b.id,
       b.name,
       b.niche,
       b."brandSummary",
       b.audience,
       c."mongodbUri",
       c."mongodbDb"
     from "Business" b
     join "AppConfig" c on c."businessId" = b.id
     where b.slug = $1
     limit 1`,
    ["zyho-store"]
  );

  const row = result.rows[0];

  if (!row) {
    throw new Error('Business slug "zyho-store" not found.');
  }

  const mongoUri = String(row.mongodbUri ?? "").trim();
  const mongoDb = String(row.mongodbDb ?? "").trim();

  if (!mongoUri || !mongoDb) {
    throw new Error("Zyho Store MongoDB config is empty.");
  }

  mongo = new MongoClient(mongoUri, {
    serverSelectionTimeoutMS: 20000,
    connectTimeoutMS: 20000,
    socketTimeoutMS: 60000
  });

  await mongo.connect();

  const profiles = mongo.db(mongoDb).collection("creator_profiles");
  const now = new Date();

  await profiles.updateOne(
    {
      creatorId: row.id,
      platform: "threads"
    },
    {
      $set: {
        creatorId: row.id,
        platform: "threads",
        name: row.name || "Zyho Store",
        niche: row.niche || "",
        brandSummary: row.brandSummary || "",
        audience: row.audience || "",
        objective: "authority",
        defaultRole: "owner",
        defaultTone: "sharp",
        defaultDraftType: "single_post",
        postsPerDay: 1,
        planningDays: 3,
        scheduleSlots: [
          { label: "Siang", time: "12:15" },
          { label: "Malam", time: "19:15" }
        ],
        autoGenerateDrafts: false,
        draftScheduleSlots: [{ label: "Pagi", time: "07:30" }],
        generateImages: false,
        imageAspectRatio: "1:1",
        updatedAt: now
      },
      $setOnInsert: {
        approvalPhone: "",
        createdAt: now
      },
      $unset: {
        imageModel: ""
      }
    },
    { upsert: true }
  );

  console.log(`Zyho Store Threads creator profile set to single_post. businessId=${row.id}`);
} finally {
  await mongo?.close();
  await pg.end();
}

