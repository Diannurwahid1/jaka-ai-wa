import { Client as PgClient } from "pg";
import { MongoClient } from "mongodb";

const databaseUrl = process.env.DATABASE_URL?.trim();

if (!databaseUrl) {
  console.error("DATABASE_URL is required.");
  process.exit(1);
}

const pg = new PgClient({ connectionString: databaseUrl });
await pg.connect();

let mongo;

try {
  const result = await pg.query(
    `select
       b.id,
       b.name,
       b.niche,
       b."brandSummary",
       b.audience,
       c."mongodbUri",
       c."mongodbDb"
     from "Business" b
     join "AppConfig" c on c."businessId" = b.id
     where b.slug = $1
     limit 1`,
    ["zyho-store"]
  );

  const row = result.rows[0];

  if (!row) {
    throw new Error('Business slug "zyho-store" not found.');
  }

  const mongoUri = String(row.mongodbUri ?? "").trim();
  const mongoDb = String(row.mongodbDb ?? "").trim();

  if (!mongoUri || !mongoDb) {
    throw new Error("Zyho Store MongoDB config is empty.");
  }

  mongo = new MongoClient(mongoUri, {
    serverSelectionTimeoutMS: 20000,
    connectTimeoutMS: 20000,
    socketTimeoutMS: 60000
  });

  await mongo.connect();

  const profiles = mongo.db(mongoDb).collection("creator_profiles");
  const now = new Date();
  const publishSlots = [
    { label: "Pagi 05", time: "05:15" },
    { label: "Pagi 07", time: "07:15" },
    { label: "Pagi 09", time: "09:15" },
    { label: "Siang 12", time: "12:15" },
    { label: "Siang 14", time: "14:15" },
    { label: "Sore 17", time: "17:15" },
    { label: "Malam 19", time: "19:15" },
    { label: "Malam 20", time: "20:15" },
    { label: "Malam 22", time: "22:15" }
  ];
  const commerceSlot = (label, time, angle, focus = "auto", style = "auto") => ({
    label,
    time,
    source: "commerce",
    commerceFocus: focus,
    commerceAngle: angle,
    commerceStyle: style,
    commerceLength: "short",
    commerceProductId: "",
    commerceVoucherId: "",
    commercePromoId: "",
    commerceIncludeVoucher: true,
    commerceIncludePromo: true,
    autoApprove: true
  });
  const draftSlots = [
    commerceSlot("Pagi Informative", "05:05", "promo informatif", "education", "workflow-tip"),
    commerceSlot("Pagi Random", "07:05", "promo informatif", "auto", "auto"),
    commerceSlot("Pagi Promo", "09:05", "promo informatif", "promo", "deal-alert"),
    commerceSlot("Siang Promo", "12:05", "promo informatif", "promo", "deal-alert"),
    commerceSlot("Siang Random", "14:05", "promo informatif", "auto", "auto"),
    commerceSlot("Sore Edukasi", "17:05", "student productivity", "education", "workflow-tip"),
    commerceSlot("Malam Promo", "19:05", "urgency tanpa hard selling", "promo", "casual-restock"),
    commerceSlot("Malam Random", "20:05", "promo informatif", "auto", "auto"),
    commerceSlot("Malam Promo", "22:05", "urgency tanpa hard selling", "promo", "deal-alert")
  ];

  await profiles.updateOne(
    {
      creatorId: row.id,
      platform: "threads"
    },
    {
      $set: {
        creatorId: row.id,
        platform: "threads",
        name: row.name || "Zyho Store",
        niche: row.niche || "",
        brandSummary: row.brandSummary || "",
        audience: row.audience || "",
        objective: "authority",
        defaultRole: "owner",
        defaultTone: "sharp",
        defaultDraftType: "single_post",
        postsPerDay: 9,
        planningDays: 3,
        scheduleSlots: publishSlots,
        autoGenerateDrafts: true,
        draftScheduleSlots: draftSlots,
        generateImages: false,
        imageAspectRatio: "1:1",
        updatedAt: now
      },
      $setOnInsert: {
        approvalPhone: "",
        createdAt: now
      },
      $unset: {
        imageModel: ""
      }
    },
    { upsert: true }
  );

  console.log(`Zyho Store Threads creator profile set to single_post. businessId=${row.id}`);
} finally {
  await mongo?.close();
  await pg.end();
}
